const express = require('express');
const PDFDocument = require('pdfkit');
const pool = require('../db');
const { logAudit } = require('../audit');
const { requireLogin, requireRole } = require('../middleware/auth');

const router = express.Router();
router.use(requireLogin);

const fmt = d => new Date(d).toLocaleString('en-PH', { timeZone: 'Asia/Manila', hour12: true });

// Per-case chain-of-custody report (PDF).
// This is NOT the audit log: it only shows ONE case and the evidence under it.
router.get('/:id/report.pdf', requireRole('investigator', 'custodian'), async (req, res) => {
  const caseId = Number(req.params.id);
  if (!Number.isInteger(caseId)) return res.status(400).json({ error: 'Bad case id' });

  const c = await pool.query(
    `SELECT c.*, u.full_name AS created_by_name FROM cases c JOIN users u ON u.id = c.created_by WHERE c.id = $1`, [caseId]);
  if (c.rowCount === 0) return res.status(404).json({ error: 'Case not found' });
  const kase = c.rows[0];

  // Custodians may only generate reports for cases where they actually held or handled evidence.
  if (req.user.role === 'custodian') {
    const involved = await pool.query(
      `SELECT 1 FROM evidence e
       WHERE e.case_id = $1 AND (e.current_custodian_id = $2 OR e.pending_custodian_id = $2 OR EXISTS (
         SELECT 1 FROM custody_events ce WHERE ce.evidence_id = e.id AND (ce.from_user = $2 OR ce.to_user = $2)))
       LIMIT 1`, [caseId, req.user.id]);
    if (involved.rowCount === 0) return res.status(403).json({ error: 'You have no custody involvement in this case' });
  }

  const ev = await pool.query(
    `SELECT e.*, cu.full_name AS custodian_name, cu.username AS custodian_username
     FROM evidence e LEFT JOIN users cu ON cu.id = e.current_custodian_id
     WHERE e.case_id = $1 ORDER BY e.registered_at`, [caseId]);

  const events = await pool.query(
    `SELECT ce.evidence_id, ce.event_type, ce.to_office, ce.note, ce.created_at,
            fu.username AS from_user, tu.username AS to_user
     FROM custody_events ce
     LEFT JOIN users fu ON fu.id = ce.from_user
     LEFT JOIN users tu ON tu.id = ce.to_user
     WHERE ce.evidence_id = ANY($1::uuid[]) ORDER BY ce.created_at, ce.id`,
    [ev.rows.map(e => e.id)]);

  const doc = new PDFDocument({ size: 'A4', margin: 50, bufferPages: true });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `inline; filename="custody-report-${kase.case_number}.pdf"`);
  doc.pipe(res);

  // Header: case number and name at the top
  doc.fontSize(10).fillColor('#555').text('CHAIN-OF-CUSTODY REPORT', { align: 'center' });
  doc.moveDown(0.3);
  doc.fontSize(18).fillColor('#000').text(`Case No. ${kase.case_number}`, { align: 'center' });
  doc.fontSize(14).text(kase.case_name, { align: 'center' });
  doc.moveDown(0.8);
  doc.fontSize(10).fillColor('#000');
  doc.text(`Case type: ${kase.case_type}`);
  doc.text(`Case status: ${kase.status}`);
  doc.text(`Opened by: ${kase.created_by_name} on ${fmt(kase.created_at)}`);
  doc.text(`Report generated by: ${req.user.username} (${req.user.role}) on ${fmt(new Date())}`);
  doc.text(`Total evidence items: ${ev.rowCount}`);
  doc.moveDown();
  doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#999').stroke();
  doc.moveDown();

  if (ev.rowCount === 0) doc.text('No evidence has been registered under this case.');

  ev.rows.forEach((e, i) => {
    const hist = events.rows.filter(x => x.evidence_id === e.id);
    const lastCheck = [...hist].reverse().find(x => x.event_type === 'verified' || x.event_type === 'verification_failed');
    const status = !lastCheck ? 'NOT YET VERIFIED'
      : lastCheck.event_type === 'verified' ? `VERIFIED (${fmt(lastCheck.created_at)})`
      : `TAMPERED / FAILED (${fmt(lastCheck.created_at)})`;

    if (doc.y > 650) doc.addPage();
    doc.fontSize(12).fillColor('#000').text(`Evidence ${i + 1}: ${e.file_name}`, { underline: true });
    doc.fontSize(9).fillColor('#000');
    doc.text(`Evidence ID: ${e.id}`);
    doc.text(`Description: ${e.description || '-'}`);
    doc.text(`File size: ${e.size_bytes} bytes`);
    doc.text(`SHA-256: ${e.sha256}`);
    doc.text(`Registered: ${fmt(e.registered_at)}`);
    doc.text(`Current custodian: ${e.custodian_name || '-'} (${e.custodian_username || '-'})`);
    doc.text(`Item status: ${e.status}`);
    doc.fillColor(lastCheck && lastCheck.event_type === 'verification_failed' ? '#b00020' : '#000')
       .text(`Verification status: ${status}`).fillColor('#000');
    doc.moveDown(0.4);
    doc.text('Custody history:', { underline: false });
    hist.forEach(h => {
      let line = `  - ${fmt(h.created_at)}  ${h.event_type.toUpperCase()}`;
      if (h.from_user) line += `  by ${h.from_user}`;
      if (h.to_user) line += `  to ${h.to_user}`;
      if (h.to_office) line += `  to office: ${h.to_office}`;
      if (h.note) line += `  (${h.note})`;
      doc.text(line);
    });
    doc.moveDown();
  });

  // Footer with page numbers
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.page.margins.bottom = 0; // lets the footer sit low on the page without creating a new page
    doc.fontSize(8).fillColor('#777').text(
      `Case ${kase.case_number}  |  Page ${i + 1} of ${range.count}`, 50, 800, { align: 'center', width: 495 });
  }
  doc.end();

  await logAudit({ userId: req.user.id, action: 'REPORT_GENERATED', targetType: 'case', targetId: String(caseId), ip: req.ip });
});

module.exports = router;